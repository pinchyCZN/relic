def do_bench(a):
    if not a.objs:
        print('no geometry loaded')
        return 1
    big = max(a.objs, key=lambda o: len(o.faces))
    t = time.time()
    render.shade_object(big, W, H, -0.42, 0.56, BG)
    shade = time.time() - t
    t = time.time()
    fb, n = texrender.render_parts(a.ship, W, H, -0.49, 0.42, BG)
    tex = time.time() - t
    t = time.time()
    to_ppm(fb, W, H)
    pack = time.time() - t
    print('%dx%d' % (W, H))
    print('  shade_object obj%-3d  %6.1f ms' % (big.index, shade * 1000))
    print('  ship textured %3d tri %6.1f ms' % (n, tex * 1000))
    print('  to_ppm               %6.1f ms' % (pack * 1000))
    print('  geometry frame       %6.1f ms -> %5.1f fps'
          % ((shade + pack) * 1000, 1.0 / (shade + pack)))
    print('  ship frame           %6.1f ms -> %5.1f fps'
          % ((tex + pack) * 1000, 1.0 / (tex + pack)))
    return 0


def do_shot(a, path, size, bend=None, yaw=24.0, pitch=-28.0,
            zoom=1.0, beams=False, phase=0):
    if not a.ship:
        print('no ship: %s' % '; '.join(a.errors))
        return 1
    a.set_bend(bend)
    sw, sh = size
    t = time.time()
    parts = [x for x in a.ship if x['group'] == 'ship']
    bl = (lightning.BEAMS_A + lightning.BEAMS_B) if beams else None
    fb, n = texrender.render_parts(parts, sw, sh, math.radians(pitch),
                                   math.radians(yaw), BG, True,
                                   zoom, bl, phase)
    chunkimg.write_png(path, sw, sh,
                       [bytes(fb[y * sw * 3:(y + 1) * sw * 3])
                        for y in range(sh)])
    print('%s  %dx%d  %d tris  %.1f s' % (path, sw, sh, n, time.time() - t))
    return 0


