#!/usr/bin/env python
"""RELIC asset viewer - look at what has actually been decoded.

    py -3.10 sim/run.py                 start on part 1
    py -3.10 sim/run.py --part 6        start on a given part
    py -3.10 sim/run.py --geo           the geometry inspector
    py -3.10 sim/run.py --tex           the texture inspector
    py -3.10 sim/run.py --list          the part list, then exit
    py -3.10 sim/run.py --bench         time a frame on each page, no window
    py -3.10 sim/run.py --shot FILE     render the ship big to a PNG and exit
    py -3.10 sim/run.py --shot FILE --size 1920x1440
    py -3.10 sim/run.py --shot FILE --bend 247 --yaw 30 --pitch -20

[ and ] step through the demo's parts, in the order
docs/parts.txt section 2 lists them. A part we have read but not
transcribed draws a card saying so rather than an approximation.

F1 toggles an on-screen key list. Everything else is in that list.

WHAT IS THE DEMO'S AND WHAT IS OURS

   THE DEMO'S   the vertices, the topology, the texels, and the
                texture coordinates - which are not stored but
                generated by sim/texmap.py, transcribed from the
                demo's own Uv_ProjRotatedXY.

   OURS         the camera, the fit-to-window scale, the resolution,
                the painter ordering, and on the geometry page the
                lighting and the two-tone face colours, which are
                invented to make shape legible.

   THE SHIP PAGE IS THE FAITHFUL ONE. It uses the demo's geometry,
   the demo's textures and the demo's mapping, and differs from what
   an Amiga showed only by NOT throwing information away - see the
   note in sim/texrender.py. The geometry page is a shape inspector
   and its colours mean nothing.

PERFORMANCE

   Everything is loaded and decoded ONCE at startup and cached: chunk
   bytes, textures as flat RGB, the parsed geometry, and the generated
   UVs. A redraw touches no file.

   The blit is a raw P6 PPM handed to Tk as bytes. The obvious
   tkinter route - PhotoImage.put with a string of "#rrggbb" tokens -
   makes Tk parse about 3.4 MB of text per frame and costs 0.47 s
   against 0.001 s for the same pixels as PPM. Do not "simplify" the
   blit back.

   Dragging the ship falls back to flat shading, which is about
   fifty times cheaper than texture mapping; the textured frame is
   drawn when the mouse is released.

Stdlib only - tkinter and a PPM blit, no PIL.
"""

