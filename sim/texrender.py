#!/usr/bin/env python
"""Texture-mapped rendering of RELIC's geometry, at any resolution.

What is the demo's, and what is ours:

   THE DEMO'S    the vertices, the topology, the texels, and the
                 texture coordinates - which are not stored but
                 generated by sim/texmap.py, transcribed from
                 Uv_ProjRotatedXY.

   OURS          the camera, the fit-to-window scale, the resolution,
                 and the decision to show 8-bit colour.

WHY THIS LOOKS BETTER THAN THE DEMO DID, and why that is honest rather
than cheating: the demo's own path is 160x100 at six-bit channels,
encoded to HAM8 and shown 640 wide, so four screen pixels share one
rendered pixel and the colour is rebuilt by a chain of per-pixel
modifies. Every one of those steps is a loss. None of them is in the
DATA. Rendering the same vertices and the same texels at full
resolution is not inventing anything - it is declining to throw away
what the assets already contain. docs/subsystems/display.txt has the
chain this skips.

AFFINE MAPPING IS EXACT HERE. The demo interpolates u and v linearly
across a span after a perspective divide at the vertices, which warps
large near-camera triangles. This viewer projects orthographically, and
under an orthographic projection linear interpolation is correct. So
the mapping below is not an approximation of the demo's - it is the
same mapping without the error the demo's perspective step introduces.

u and v WRAP, never clamp - docs/subsystems/renderer.txt section 3.
"""

import math


def build_texture_256(chunk, offset):
    """A 256 x 256 RGB page starting at `offset` in a texture chunk.

    THE SAMPLER ALWAYS ADDRESSES 256 x 256. Rast_FillSpansTextured
    builds its index as (v & 0xff00) | (u & 0x00ff), so v is masked to
    eight bits no matter how tall the texture really is - see
    docs/subsystems/renderer.txt section 3.

    That is why Fshiptextures' third and fourth sub-textures, 0x20000
    each, are not really separate images: sampling from the third
    base with v past 127 runs straight into the fourth. Whatever runs
    off the end of the chunk is black here, which is the one place
    this differs from the hardware - it would read neighbouring
    memory.
    """
    need = 256 * 256 * 4
    d = chunk[offset:offset + need]
    if len(d) < need:
        d = d + bytes(need - len(d))
    return build_texture_rgb(d, 256, 256)


def build_texture_rgb(d, width, height):
    """4-byte (R, G, pad, B) 6-bit texels to flat 8-bit RGB bytes."""
    out = bytearray(width * height * 3)
    j = 0
    for i in range(width * height):
        o = i * 4
        r = d[o]
        g = d[o + 1]
        b = d[o + 3]
        out[j] = (r << 2) | (r >> 4)
        out[j + 1] = (g << 2) | (g >> 4)
        out[j + 2] = (b << 2) | (b >> 4)
        j += 3
    return bytes(out)


def fill_tri_tex(fb, w, h, p0, p1, p2, uv0, uv1, uv2, tex, shade=256):
    """Affine texture-map one triangle. 256x256 texture, wrapping.

    p* are (x, y) floats in screen space, uv* are (u, v) integers from
    texmap. shade is a 0..256 multiplier applied per channel; 256 is
    unshaded, which is what the demo does - its textures are pre-lit.
    """
    v = [(p0[0], p0[1], uv0[0], uv0[1]),
         (p1[0], p1[1], uv1[0], uv1[1]),
         (p2[0], p2[1], uv2[0], uv2[1])]
    v.sort(key=lambda e: e[1])
    (ax, ay, au, av), (bx, by, bu, bv), (cx, cy, cu, cv) = v
    if cy - ay < 1e-9:
        return

    y0 = max(0, int(math.ceil(ay)))
    y1 = min(h - 1, int(math.floor(cy)))
    if y1 < y0:
        return

    iac = 1.0 / (cy - ay)
    dx_ac = (cx - ax) * iac
    du_ac = (cu - au) * iac
    dv_ac = (cv - av) * iac
    if by - ay > 1e-9:
        iab = 1.0 / (by - ay)
        dx_ab, du_ab, dv_ab = ((bx - ax) * iab, (bu - au) * iab,
                               (bv - av) * iab)
    else:
        dx_ab = du_ab = dv_ab = 0.0
    if cy - by > 1e-9:
        ibc = 1.0 / (cy - by)
        dx_bc, du_bc, dv_bc = ((cx - bx) * ibc, (cu - bu) * ibc,
                               (cv - bv) * ibc)
    else:
        dx_bc = du_bc = dv_bc = 0.0

    lit = shade != 256
    for y in range(y0, y1 + 1):
        t = y - ay
        xl = ax + dx_ac * t
        ul = au + du_ac * t
        vl = av + dv_ac * t
        if y < by:
            xr = ax + dx_ab * t
            ur = au + du_ab * t
            vr = av + dv_ab * t
        else:
            s = y - by
            xr = bx + dx_bc * s
            ur = bu + du_bc * s
            vr = bv + dv_bc * s
        if xl > xr:
            xl, xr = xr, xl
            ul, ur = ur, ul
            vl, vr = vr, vl

        ixl = int(math.ceil(xl))
        ixr = int(math.floor(xr))
        span = xr - xl
        if span > 1e-9:
            du = (ur - ul) / span
            dv = (vr - vl) / span
        else:
            du = dv = 0.0
        if ixl < 0:
            ul += du * (0 - xl)
            vl += dv * (0 - xl)
            ixl = 0
        else:
            ul += du * (ixl - xl)
            vl += dv * (ixl - xl)
        if ixr > w - 1:
            ixr = w - 1
        n = ixr - ixl + 1
        if n <= 0:
            continue

        # 16.16 accumulators so the inner loop is integer only
        u = int(ul * 65536.0)
        vv = int(vl * 65536.0)
        iu = int(du * 65536.0)
        iv = int(dv * 65536.0)
        o = (y * w + ixl) * 3
        if lit:
            for _ in range(n):
                i = ((((vv >> 16) & 255) << 8) | ((u >> 16) & 255)) * 3
                fb[o] = (tex[i] * shade) >> 8
                fb[o + 1] = (tex[i + 1] * shade) >> 8
                fb[o + 2] = (tex[i + 2] * shade) >> 8
                o += 3
                u += iu
                vv += iv
        else:
            for _ in range(n):
                i = ((((vv >> 16) & 255) << 8) | ((u >> 16) & 255)) * 3
                fb[o:o + 3] = tex[i:i + 3]
                o += 3
                u += iu
                vv += iv


def render_parts(parts, w, h, ax, ay, bg=(10, 10, 14), cull=True,
                 zoom=1.0, beams=None, phase=0):
    """Draw an assembled model.

    parts is a list of dicts with:
        obj     a geom.Obj
        uvs     [(u,v) x3] per face, from texmap
        tex     flat RGB bytes for its texture
        verts   optional replacement vertices - the struts are bent by
                texmap.mesh_deform_strut before they are drawn, while
                their UVs still come from the rest pose
        zoff    optional world z offset in 16.16 units; the ship needs
                NONE, its parts already abut in object space
        cull    +1 drop one winding, -1 drop the other, 0 draw both

    cull is the demo's g_CullMode, which Poly_DrawFaceList reads from
    the draw context at +0x4c:

        0   keep where the screen cross product is positive
        1   negate it first - for objects wound the other way
        2   draw everything, no backface test

    maybe_Ship_Render never writes +0x4c, and BSS starts zeroed, so
    BOTH ship parts use mode 0. They are closed solids of revolution
    and split 24/24 and 28/28 by winding, so one sign serves both.

    Pass cull=False to force two-sided drawing. That is an INSPECTION
    aid, not the demo's behaviour.

    Returns the framebuffer. Painter-sorted across ALL parts together,
    so the two ship halves interleave correctly.
    """
    import render as _r
    fb = bytearray(bytes(bg) * (w * h))

    # one shared fit across every part, so they keep their relative size
    allp = []
    for p in parts:
        zo = p.get('zoff', 0) / 65536.0
        for v in p.get('verts') or p['obj'].verts:
            vx, vy, vz = _r.to_view(v)
            allp.append(_rot((vx, vy, vz + zo), ax, ay))
    if not allp:
        return fb
    xs = [q[0] for q in allp]
    ys = [q[1] for q in allp]
    cx = (min(xs) + max(xs)) / 2.0
    cy = (min(ys) + max(ys)) / 2.0
    span = max(max(xs) - min(xs), max(ys) - min(ys), 1e-6)
    s = (min(w, h) * 0.44) / (span * 0.5) * zoom
    fit = (cx, cy, s)

    tris = []
    base = 0
    for p in parts:
        o = p['obj']
        n = len(p.get('verts') or o.verts)
        pts3 = allp[base:base + n]
        base += n
        scr = [(w / 2.0 + (q[0] - cx) * s, h / 2.0 - (q[1] - cy) * s)
               for q in pts3]
        for fi, f in enumerate(o.faces):
            ia, ib, ic = f.corners
            if max(ia, ib, ic) >= n:
                continue
            pa, pb, pc = scr[ia], scr[ib], scr[ic]
            sign = p.get('cull', 1) if cull else 0
            if sign:
                area = ((pb[0] - pa[0]) * (pc[1] - pa[1])
                        - (pb[1] - pa[1]) * (pc[0] - pa[0]))
                if area * sign >= 0:
                    continue
            depth = max(pts3[ia][2], pts3[ib][2], pts3[ic][2])
            if p['tex'] is None:
                # FUN_002d155c sets these faces to mode 1, the flat
                # untextured path. Flat here too; the colour is ours.
                va, vb, vc = pts3[ia], pts3[ib], pts3[ic]
                ux, uy, uz = (vb[0]-va[0], vb[1]-va[1], vb[2]-va[2])
                wx, wy, wz = (vc[0]-va[0], vc[1]-va[1], vc[2]-va[2])
                nx = uy*wz - uz*wy
                ny = uz*wx - ux*wz
                nz = ux*wy - uy*wx
                nl = math.sqrt(nx*nx + ny*ny + nz*nz) or 1.0
                lum = 0.25 + 0.75 * abs(nz / nl)
                tris.append((depth, pa, pb, pc, None, None, None,
                             bytes((int(90*lum), int(120*lum),
                                    int(165*lum)))))
                continue
            uv = p['uvs'][fi]
            if uv is None:
                continue          # the demo's range cull rejected it
            tris.append((depth, pa, pb, pc, uv[0], uv[1], uv[2], p['tex']))

    tris.sort(key=lambda e: -e[0])
    import render as _rr
    for _d, pa, pb, pc, u0, u1, u2, tex in tris:
        if u0 is None:
            _rr.fill_tri(fb, w, h, pa, pb, pc, tex)
        else:
            fill_tri_tex(fb, w, h, pa, pb, pc, u0, u1, u2, tex)
    if beams:
        draw_beams(fb, w, h, ax, ay, fit, beams, phase)
    return fb, len(tris)


def draw_beams(fb, w, h, ax, ay, fit, beams, phase):
    """Stroke the six lightning beams over an already-drawn frame.

    Each beam is two object-space points. They project through the
    SAME fit the meshes used, so a bolt lands on the hull it comes
    out of at any camera angle and zoom.

    DRAWN AT THE WINDOW'S RESOLUTION, NOT THE DEMO'S 160 x 100. That
    is safe because every term in Beam_BuildBoltPath scales with the
    bolt's own pixel length - the jitter and the node radius both -
    so the shape is resolution independent. The two that do not are
    Draw_LineAA's three-pixel width and the radius floor of 4, so a
    bolt is relatively finer here than on the Amiga.
    """
    import lightning as _l
    import render as _r
    cx, cy, s = fit
    light = bytearray(w * h)
    xs = []
    ys = []
    for i, (a, b) in enumerate(beams):
        pts = []
        for v in (a, b):
            vx, vy, vz = _r.to_view(v)
            q = _rot((vx, vy, vz), ax, ay)
            pts.append((int(w / 2.0 + (q[0] - cx) * s),
                        int(h / 2.0 - (q[1] - cy) * s)))
        (x0, y0), (x1, y1) = pts
        xs += [x0, x1]
        ys += [y0, y1]
        _l.draw_bolt(light, x0, y0, x1, y1,
                     (phase + i * 0x2a1) & 0x1fff, i * 7, w, h)
    if not xs:
        return
    pad = 48
    _l.resolve_into(fb, light, w, h,
                    (min(xs) - pad, min(ys) - pad,
                     max(xs) + pad, max(ys) + pad))


def _rot(v, ax, ay):
    x, y, z = v
    ca, sa = math.cos(ay), math.sin(ay)
    x, z = x * ca + z * sa, -x * sa + z * ca
    ca, sa = math.cos(ax), math.sin(ax)
    y, z = y * ca - z * sa, y * sa + z * ca
    return (x, y, z)


def render_parts_flat(parts, w, h, ax, ay, bg=(10, 10, 14), cull=True,
                      zoom=1.0, beams=None, phase=0):
    """Same gather and ordering as render_parts, but flat-shaded.

    This is the drag preview. It exists because texture mapping costs
    about 200 ms a frame in Python and dragging needs to feel live;
    the textured frame is drawn when the mouse is released.

    It builds ONE framebuffer for every part rather than compositing
    per-part images, because a per-pixel composite in Python costs
    more than the shading it was meant to save.
    """
    import math as _m
    import render as _r
    fb = bytearray(bytes(bg) * (w * h))
    allp = []
    for p in parts:
        zo = p.get('zoff', 0) / 65536.0
        for v in p.get('verts') or p['obj'].verts:
            vx, vy, vz = _r.to_view(v)
            allp.append(_rot((vx, vy, vz + zo), ax, ay))
    if not allp:
        return fb, 0
    xs = [q[0] for q in allp]
    ys = [q[1] for q in allp]
    cx = (min(xs) + max(xs)) / 2.0
    cy = (min(ys) + max(ys)) / 2.0
    span = max(max(xs) - min(xs), max(ys) - min(ys), 1e-6)
    s = (min(w, h) * 0.44) / (span * 0.5) * zoom

    lx, ly, lz = 0.35, 0.55, -0.75
    ln = _m.sqrt(lx * lx + ly * ly + lz * lz)
    lx, ly, lz = lx / ln, ly / ln, lz / ln

    tris = []
    base = 0
    for p in parts:
        o = p['obj']
        n = len(p.get('verts') or o.verts)
        pts3 = allp[base:base + n]
        base += n
        scr = [(w / 2.0 + (q[0] - cx) * s, h / 2.0 - (q[1] - cy) * s)
               for q in pts3]
        sign = p.get('cull', 1) if cull else 0
        for f in o.faces:
            ia, ib, ic = f.corners
            if max(ia, ib, ic) >= n:
                continue
            pa, pb, pc = scr[ia], scr[ib], scr[ic]
            if sign:
                area = ((pb[0] - pa[0]) * (pc[1] - pa[1])
                        - (pb[1] - pa[1]) * (pc[0] - pa[0]))
                if area * sign >= 0:
                    continue
            va, vb, vc = pts3[ia], pts3[ib], pts3[ic]
            ux, uy, uz = vb[0] - va[0], vb[1] - va[1], vb[2] - va[2]
            wx, wy, wz = vc[0] - va[0], vc[1] - va[1], vc[2] - va[2]
            nx = uy * wz - uz * wy
            ny = uz * wx - ux * wz
            nz = ux * wy - uy * wx
            nl = _m.sqrt(nx * nx + ny * ny + nz * nz)
            if nl < 1e-12:
                continue
            lum = 0.20 + 0.80 * abs((nx * lx + ny * ly + nz * lz) / nl)
            col = bytes((int(110 * lum), int(150 * lum), int(205 * lum)))
            tris.append((max(va[2], vb[2], vc[2]), col, pa, pb, pc))

    tris.sort(key=lambda e: -e[0])
    import render as _r
    for _d, col, pa, pb, pc in tris:
        _r.fill_tri(fb, w, h, pa, pb, pc, col)
    return fb, len(tris)
